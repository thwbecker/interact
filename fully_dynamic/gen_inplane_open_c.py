"""Generate the C version of the opening (tensile) point source of the 2-D in-plane kernels
(src/rsf_solve/fd_kernels_open_gen.c), from the same expressions as gen_inplane_open.py
(which writes the Python version, inplane_kernel_open.py). The generated field carries the
opposite sign of the physical one, as the Python version.
Usage: python3 gen_inplane_open_c.py [output path]"""
import sys
import sympy as sp
import gen_inplane as g


def fields():
    out = {}
    x, y = g.x, g.y
    for tag, wb in (("ps", True), ("p", False)):
        Gh = [[g.Ghat(i, j, wb) for j in range(2)] for i in range(2)]
        u = [g.lam*sp.diff(Gh[i][0], x) + (g.lam + 2*g.mu)*sp.diff(Gh[i][1], y) for i in range(2)]
        exx = sp.diff(u[0], x)
        eyy = sp.diff(u[1], y)
        exy = (sp.diff(u[0], y) + sp.diff(u[1], x))/2
        div = exx + eyy
        out[tag] = (g.lam*div + 2*g.mu*exx, 2*g.mu*exy, g.lam*div + 2*g.mu*eyy)
    return out


def main(path):
    out = fields()
    lines = ["/* Generated by fully_dynamic/gen_inplane_open_c.py; do not edit by hand.",
             "   Stresses (sxx, sxy, syy) at (x, y), time t, from a point opening dislocation at the origin",
             "   (opening across y = 0) created at t = 0 with unit opening rate, with the sign convention of",
             "   the prototype's generated fields (opposite to the physical one). _ps: inside the S front,",
             "   _p: between the P and the S front. */",
             "#include <math.h>", ""]
    for tag in ("ps", "p"):
        reps, red = sp.cse(out[tag], optimizations="basic")
        lines.append(f"void fd_sig_open_{tag}(double x, double y, double t, double alpha, double beta, double rho, double *s)")
        lines.append("{")
        for sym, e in reps:
            lines.append(f"  double {sym};")
        for sym, e in reps:
            lines.append(f"  {sym} = {sp.ccode(e)};")
        for k, e in enumerate(red):
            lines.append(f"  s[{k}] = {sp.ccode(e)};")
        lines.append("}")
        lines.append("")
    open(path, "w").write("\n".join(lines))
    print("wrote", path)


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "../src/rsf_solve/fd_kernels_open_gen.c")
