"""
Large-time expansion of the Tada and Madariaga (2001) in-plane primitives
I11, I12, I22 (their eqs A4-A6) for beta t / r >> 1 (both waves arrived):

    I(x1, x2, t) = c3 t^3 + c1 t + c_{-1} t^-1 + c_{-3} t^-3 + c_{-5} t^-5 + ...

Verified here: c3 == 0 (the P and S t^3 terms cancel) and c1 equals the
static primitive I_st of Ando et al. (2007) eqs (19)-(21) up to the factor
-mu/(2 beta). Generated code evaluates the dynamic correction of a segment,

    W = (-mu/(2 beta)) * sum_{k=1,3,5} [c_{-k}(x+a) - c_{-k}(x-a)]
                          * [(t+dt)^-k - t^-k],

which is free of the t^3 cancellation that limits the closed form.
I12 is treated for x1 > 0 and extended by the odd symmetry of its
non-constant part (I12(-x1) = 1 - I12(|x1|) when both H terms are 1); the
constant drops out of the t^-k coefficients anyway.
"""
import sympy as sp

x1, x2 = sp.symbols("x1 x2", real=True)
t, eps = sp.symbols("t epsilon", positive=True)
al, be = sp.symbols("alpha beta", positive=True)
p = be / al
r = sp.sqrt(x1**2 + x2**2)
gL = (al * t / r) * sp.sqrt(1 - (r / (al * t)) ** 2)
gT = (be * t / r) * sp.sqrt(1 - (r / (be * t)) ** 2)
q = 2 * (3 * x1**2 - x2**2) / (3 * r**2)
q2 = 2 * (3 * x2**2 - x1**2) / (3 * r**2)
a1 = x1**2 / r**2; a2 = x2**2 / r**2
X = sp.Symbol("X", positive=True)   # |x1| for the I12 branch
rX = sp.sqrt(X**2 + x2**2)
gLX = (al * t / rX) * sp.sqrt(1 - (rX / (al * t)) ** 2); gTX = (be * t / rX) * sp.sqrt(1 - (rX / (be * t)) ** 2)
q2X = 2 * (3 * x2**2 - X**2) / (3 * rX**2); a2X = x2**2 / rX**2

I11 = (-(1 / sp.pi) * (2 * x2 / r) * p * (q * p**2 * gL**3 + (1 - 2 * a2 * p**2) * gL)
       + (1 / sp.pi) * (2 * x2 / r) * (q * gT**3 + (1 - 2 * a2) * gT))
I22 = ((1 / sp.pi) * (2 * x2 / r) * p * (q * p**2 * gL**3 + (2 * a1 * p**2 - 1) * gL)
       - (1 / sp.pi) * (2 * x2 / r) * (q * gT**3 + (2 * a1 - 1) * gT))
# I12 for x1 = X > 0 (constant 1 omitted)
I12p = (-(1 / sp.pi) * (2 * X / rX) * p * (q2X * p**2 * gLX**3 + 2 * a2X * p**2 * gLX)
        + (1 / sp.pi) * ((2 * X / rX) * (q2X * gTX**3 + 2 * a2X * gTX) - sp.acos(X / (be * t * sp.sqrt(1 - (x2 / (be * t)) ** 2)))))


def coeffs(expr, order=5):
    e = sp.series(expr.subs(t, 1 / eps), eps, 0, order + 1).removeO()
    e = sp.expand(e)
    c = {k: 0 for k in range(-3, order + 1)}
    for term in e.as_ordered_terms():
        co, ex = term.as_coeff_exponent(eps)
        c[int(ex)] = c.get(int(ex), 0) + co
    return {k: sp.simplify(v) for k, v in c.items()}


def main():
    out = {}
    for name, expr in (("11", I11), ("22", I22), ("12p", I12p)):
        c = coeffs(expr)
        c3, c1 = c[-3], c[-1]
        assert sp.simplify(c3) == 0, ("t^3 term does not cancel", name, c3)
        out[name] = c
        print(name, "t^3 cancels; c1 =", c1)
    # check c1 against Ando et al. (2007) eqs (19)-(21) (their I_st)
    Ist11 = -(2 * be / sp.pi) * (1 - p**2) * x2 / r**2 * (1 + 2 * x1**2 / r**2)
    Ist22 = -(2 * be / sp.pi) * (1 - p**2) * x2 / r**2 * (1 - 2 * x1**2 / r**2)
    Ist12 = -(2 * be / sp.pi) * (1 - p**2) * X / rX**2 * (x2**2 - X**2) / rX**2
    for name, ref in (("11", Ist11), ("22", Ist22), ("12p", Ist12)):
        d = sp.simplify(out[name][-1] - ref)
        assert d == 0, (name, d)
    print("c1 matches the static primitives of Ando et al. (2007)")
    # generate code: coefficient functions of t^-1, t^-3, t^-5
    lines = ['"""Generated by gen_series.py; do not edit by hand."""',
             "import numpy as np", "from numpy import sqrt, pi", ""]
    for name in ("11", "22", "12p"):
        for k in (1, 3, 5):
            e = out[name][k]
            var = "X" if name == "12p" else "x1"
            lines.append(f"def c_{name}_m{k}({var}, x2, alpha, beta):")
            reps, red = sp.cse(e, optimizations="basic")
            for s_, v in reps:
                lines.append(f"    {s_} = {sp.pycode(v)}")
            lines.append(f"    return {sp.pycode(red[0])}")
            lines.append("")
    body = "\n".join(lines).replace("math.sqrt", "sqrt").replace("math.pi", "pi")
    body += '''

def _cm(name, k, x1, x2, alpha, beta):
    if name == "12":
        # odd extension of the non-constant part: I12(-x1) = 1 - I12(|x1|)
        X = np.abs(x1)
        v = globals()[f"c_12p_m{k}"](X, x2, alpha, beta)
        return np.where(x1 >= 0, v, -v)
    return globals()[f"c_{name}_m{k}"](x1, x2, alpha, beta)


def W_series(xr, yr, t, dt, a, alpha, beta, rho):
    """Dynamic correction of a segment at large beta t / r, physical
    convention (sxx, sxy, syy):  -(mu/(2 beta)) * sum_k [c_k(x+a) - c_k(x-a)]
    * [(t+dt)^-k - t^-k], k = 1, 3, 5.  Requires beta*t > ~10 r for both
    endpoints."""
    mu = rho * beta**2
    xr = np.asarray(xr, float); yr = np.asarray(yr, float); t = np.asarray(t, float)
    xr, yr, t = np.broadcast_arrays(xr, yr, t)
    out = []
    for name in ("11", "12", "22"):
        acc = np.zeros(xr.shape)
        for k in (1, 3, 5):
            dc = _cm(name, k, xr + a, yr, alpha, beta) - _cm(name, k, xr - a, yr, alpha, beta)
            acc += dc * ((t + dt) ** (-k) - t ** (-k))
        out.append(-(mu / (2 * beta)) * acc)
    return out
'''
    with open("inplane_series.py", "w") as f:
        f.write(body)
