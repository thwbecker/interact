"""Emit src/rsf_solve/fd_series_coeffs.c from the symbolic large-time expansion
in gen_series.py (same expressions as inplane_series.py). Run from
fully_dynamic/: python3 gen_series_c.py > ../src/rsf_solve/fd_series_coeffs.c"""
import sympy as sp, importlib.util
spec = importlib.util.spec_from_file_location("gs", "gen_series.py"); gs = importlib.util.module_from_spec(spec); spec.loader.exec_module(gs)
out = {name: gs.coeffs(expr) for name, expr in (("11", gs.I11), ("22", gs.I22), ("12p", gs.I12p))}
lines = ["/* generated by fully_dynamic/gen_series_c.py from the symbolic large-time",
         "   expansion of the Tada-Madariaga primitives (see fully_dynamic/gen_series.py);",
         "   do not edit by hand. c_<ij>_m<k>: coefficient of t^-k, k = 1, 3, 5. */",
         "#include <math.h>", ""]
for name in ("11", "22", "12p"):
    for k in (1, 3, 5):
        var = "X" if name == "12p" else "x1"
        reps, red = sp.cse(out[name][k], optimizations="basic")
        lines.append(f"double fd_c_{name}_m{k}(double {var}, double x2, double alpha, double beta)")
        lines.append("{")
        for s_, v in reps:
            lines.append(f"  double {s_} = {sp.ccode(v)};")
        lines.append(f"  return {sp.ccode(red[0])};")
        lines.append("}")
        lines.append("")
print("\n".join(lines))
