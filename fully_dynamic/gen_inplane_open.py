"""Generate the opening (tensile) point source for the 2-D in-plane kernels,
companion of gen_inplane.py (same Green's function Ghat, same sign
convention as inplane_kernel.sigma_point_ramp: the generated field carries
the OPPOSITE sign of the physical one).
Point opening across the plane y = 0 at the origin, created at t = 0 with
opening rate 1 (opening = t): moment density m_xx = lambda t, m_yy =
(lambda + 2 mu) t, m_xy = 0, u_i = lambda d_x Ghat_ix + (lambda + 2 mu) d_y Ghat_iy.
Writes inplane_kernel_open.py with sigma_point_ramp_open(x, y, t, alpha, beta, rho)."""
import sympy as sp
import gen_inplane as g

def generate(path="inplane_kernel_open.py"):
    out = {}
    x, y = g.x, g.y
    for tag, wb in (("ps", True), ("p", False)):
        Gh = [[g.Ghat(i, j, wb) for j in range(2)] for i in range(2)]
        u = [g.lam*sp.diff(Gh[i][0], x) + (g.lam + 2*g.mu)*sp.diff(Gh[i][1], y) for i in range(2)]
        exx = sp.diff(u[0], x); eyy = sp.diff(u[1], y); exy = (sp.diff(u[0], y) + sp.diff(u[1], x))/2
        div = exx + eyy
        out[tag] = (g.lam*div + 2*g.mu*exx, 2*g.mu*exy, g.lam*div + 2*g.mu*eyy)
    lines = ['"""Generated by gen_inplane_open.py; do not edit by hand.',
             'Stresses at (x,y), time t, from a point opening dislocation at the origin',
             '(opening across the plane y=0) created at t=0 with unit opening rate;',
             'same sign convention as inplane_kernel.sigma_point_ramp."""',
             'import numpy as np', 'from numpy import sqrt, arccos, arccosh, pi', '']
    for tag in ("ps", "p"):
        reps, red = sp.cse(out[tag], optimizations="basic")
        lines.append(f"def _sig_{tag}(x, y, t, alpha, beta, rho):")
        for s, e in reps: lines.append(f"    {s} = {sp.pycode(e)}")
        lines.append("    return (" + ", ".join(sp.pycode(e) for e in red) + ")"); lines.append("")
    body = "\n".join(lines).replace("math.sqrt", "sqrt").replace("math.acos", "arccos").replace("math.acosh", "arccosh").replace("math.pi", "pi")
    body += '''

def sigma_point_ramp_open(x, y, t, alpha, beta, rho):
    """Vectorized over x, y, t (broadcast). Returns (sxx, sxy, syy)."""
    x = np.asarray(x, dtype=float); y = np.asarray(y, dtype=float); t = np.asarray(t, dtype=float)
    x, y, t = np.broadcast_arrays(x, y, t)
    R = np.hypot(x, y)
    mp = alpha * t > R
    ms = beta * t > R
    sxx = np.zeros(x.shape); sxy = np.zeros(x.shape); syy = np.zeros(x.shape)
    with np.errstate(all="ignore"):
        if ms.any():
            a, b, c = _sig_ps(x[ms], y[ms], t[ms], alpha, beta, rho)
            sxx[ms] = a; sxy[ms] = b; syy[ms] = c
        mpo = mp & ~ms
        if mpo.any():
            a, b, c = _sig_p(x[mpo], y[mpo], t[mpo], alpha, beta, rho)
            sxx[mpo] = a; sxy[mpo] = b; syy[mpo] = c
    return sxx, sxy, syy
'''
    open(path, "w").write(body)
    print("wrote", path)

if __name__ == "__main__":
    generate()
